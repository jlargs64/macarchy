#!/usr/bin/env node
// Regenerate the per-theme CSS and the theme cards in the site from the themes themselves.
//   node site/tools/themes.mjs
// Reads home/.config/theme/themes/*/colors.sh and writes:
//   site/css/tokens.css   between /* palettes:start */ and /* palettes:end */
//   site/index.html       between <!-- themes:start --> and <!-- themes:end -->
// Run it after adding or porting a theme. The site's JS reads the theme list from the cards.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const themesDir = resolve(here, "../../home/.config/theme/themes");
const tokensPath = resolve(here, "../css/tokens.css");
const pagePath = resolve(here, "../index.html");

// Themes that were not made with theme-port, and how their card labels them.
const LABELS = {
  "retro-82": "custom · 1982 arcade CRT",
  "kanagawa-wave": "upstream",
  "catppuccin-mocha": "upstream",
};
const KEYS = ["BG", "FG", "ACCENT", "ACCENT2", "MUTED", "RED", "GREEN", "YELLOW", "BLUE", "MAGENTA", "CYAN"];

function luminance(hex) {
  const [r, g, b] = [0, 2, 4].map(i => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map(c => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const themes = readdirSync(themesDir, { withFileTypes: true })
  .filter(d => d.isDirectory())
  .map(d => {
    const src = readFileSync(resolve(themesDir, d.name, "colors.sh"), "utf8");
    const c = {};
    for (const k of KEYS) {
      const m = src.match(new RegExp(`^export ${k}=([0-9a-fA-F]{6})\\s*$`, "m"));
      if (!m) throw new Error(`${d.name}/colors.sh: missing ${k}`);
      c[k] = m[1].toLowerCase();
    }
    const light = luminance(c.BG) > 0.5;
    let label = LABELS[d.name] || "ported from Omarchy";
    if (light) label += " · light";
    return { name: d.name, c, light, label };
  });

// Order: the three hand-kept themes first, then the dark ports, then the light ones, each alphabetical.
const pinned = Object.keys(LABELS);
themes.sort((a, b) => {
  const pa = pinned.indexOf(a.name), pb = pinned.indexOf(b.name);
  if (pa >= 0 || pb >= 0) return (pa < 0 ? 99 : pa) - (pb < 0 ? 99 : pb);
  if (a.light !== b.light) return a.light ? 1 : -1;
  return a.name.localeCompare(b.name);
});

const css = [
  "/* palettes:start */",
  "/* generated by site/tools/themes.mjs from home/.config/theme/themes/<name>/colors.sh; do not edit by hand */",
  ...themes.map((t, i) => {
    const sel = (i === 0 ? ":root,\n" : "") + `:root[data-theme="${t.name}"]`;
    const c = t.c;
    return `${sel} {\n  --t-bg:#${c.BG}; --t-fg:#${c.FG}; --t-accent:#${c.ACCENT}; --t-accent2:#${c.ACCENT2}; --t-muted:#${c.MUTED};\n  --t-red:#${c.RED}; --t-green:#${c.GREEN}; --t-yellow:#${c.YELLOW}; --t-blue:#${c.BLUE}; --t-magenta:#${c.MAGENTA}; --t-cyan:#${c.CYAN};\n}`;
  }),
  "",
  "/* static per-theme swatches for the theme cards (each card shows its own palette regardless of the active theme) */",
  ":root {",
  ...themes.map(t => {
    const c = t.c;
    return `  --pal-${t.name}: #${c.BG}, #${c.FG}, #${c.ACCENT}, #${c.ACCENT2}, #${c.RED}, #${c.GREEN}, #${c.BLUE}, #${c.YELLOW};`;
  }),
  "}",
  "/* palettes:end */",
].join("\n");

const cards = themes.map((t, i) =>
  `        <li><button class="theme-card" type="button" data-set-theme="${t.name}" data-mode="${t.light ? "light" : "dark"}" aria-pressed="${i === 0}"><span class="theme-card__swatch" data-pal="${t.name}" aria-hidden="true"><i></i><i></i><i></i><i></i><i></i><i></i><i></i><i></i></span><span class="theme-card__row"><span class="theme-card__name">${t.name}</span><span class="theme-card__src">${t.label}</span></span></button></li>`
).join("\n");

function splice(path, re, body) {
  const text = readFileSync(path, "utf8");
  if (!re.test(text)) { console.error(`markers not found in ${path}`); process.exit(1); }
  writeFileSync(path, text.replace(re, `$1\n${body}\n$2`));
}
splice(tokensPath, /(\/\* palettes:start \*\/)[\s\S]*?(\/\* palettes:end \*\/)/, css.split("\n").slice(1, -1).join("\n"));
splice(pagePath, /(<!-- themes:start -->)[\s\S]*?(<!-- themes:end -->)/, cards);
console.log(`themes: ${themes.length} (${themes.filter(t => t.light).length} light) → tokens.css, index.html`);
